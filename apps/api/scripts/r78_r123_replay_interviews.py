class PlainQuestionReplay(ModelProvider):
    """Replay a scripted question through the non-adaptive MainArtifact path.

    source_type DYNAMIC_GENERATED states honestly that the question was supplied
    by the test script, not autonomously generated by a live interviewer model.
    No Controller/DB behaviour is mocked.
    """
    provider_name, model_name = "replay", "R123_SCRIPTED_QUESTION"

    def __init__(self, question, expected_points, dimension):
        self.question, self.ep, self.dimension = question, list(expected_points), dimension
        self.calls = []

    async def generate(self, messages, *, schema):
        self.calls.append(schema["title"])
        raw = json.loads(messages[-1]["content"])
        payload = raw["input"] if "input" in raw else raw
        pref = payload.get("preferred_source") or {}
        src_type = pref.get("source_type") or "DYNAMIC_GENERATED"
        src_id = pref.get("source_id")
        q = dict(question=self.question, expected_points=self.ep, dimension=self.dimension,
                 difficulty=payload.get("desired_difficulty", "MEDIUM"), source_type=src_type)
        if src_type == "JOB_REQUIREMENT" and src_id is not None:
            q["job_requirement_id"] = src_id
        elif src_type == "PUBLIC_QUESTION" and src_id is not None:
            q["source_question_id"] = src_id
        elif src_type == "CANDIDATE_PROFILE":
            q["candidate_fact_ids"] = [src_id] if src_id is not None else []
            q["candidate_evidence_ids"] = []
        value = dict(recommendation="NEXT", question=q)
        return ModelResponse(json.dumps(value, ensure_ascii=False),
                             dict(input_tokens=0, output_tokens=0, total_tokens=0))


class DeterministicEvaluation(ModelProvider):
    """Grade from answer text shape only; hidden rubric never inspected."""
    provider_name, model_name = "replay", "R123_DETERMINISTIC_EVAL"

    def __init__(self, variant: str):
        self.variant, self.calls = variant, []
        if variant == "strong":
            self.dims = {d: 4 for d in DIMS}
        elif variant == "blank":
            self.dims = {d: 1 for d in DIMS}
        else:
            self.dims = dict(technical_correctness=1, coverage=1, depth=1, relevance=2, communication=2)

    async def generate(self, messages, *, schema):
        raw = json.loads(messages[-1]["content"])
        payload = raw["input"] if "input" in raw else raw
        self.calls.append(schema["title"])
        answer = payload.get("answer") or ""
        assert answer, "evaluation must carry the real answer"
        value = dict(self.dims,
                     evaluation=("回答覆盖了题目要点并给出依据。" if self.variant == "strong" else
                                 "回答表示无法给出可靠结论，缺少可评估内容。" if self.variant == "blank" else
                                 "回答包含绝对化断言且未提供证据，不能判定为正确。"),
                     covered_points=["覆盖了题目要点"] if self.variant == "strong" else [],
                     missing_points=[] if self.variant == "strong" else ["关键知识点未覆盖"],
                     factual_or_reasoning_issues=([] if self.variant == "strong" else
                         ["回答说不出可靠依据"] if self.variant == "blank" else
                         ["包含未加论证的绝对化断言"]),
                     follow_up_focus=[], next_action_recommendation="NEXT", reference_answer=None)
        return ModelResponse(json.dumps(value, ensure_ascii=False),
                             dict(input_tokens=0, output_tokens=0, total_tokens=0))


class ReplayCoach(ModelProvider):
    """Coach fixture that references the real persisted evaluation ids.
    0 model HTTP. No invented statistics: uses the same response_for builder
    audited in R121's UI acceptance (numbers derived from evaluation ids)."""
    provider_name, model_name = "replay", "R123_REPLAY_COACH"

    async def generate(self, messages, *, schema):
        from test_coach_harness import response_for
        raw = json.loads(messages[-1]["content"])
        payload = raw["input"] if "input" in raw else raw
        evals = payload.get("evaluations") or []
        ids = [e.get("id") or e.get("evaluation_id") for e in evals if isinstance(e, dict)]
        ids = [i for i in ids if i is not None]
        return ModelResponse(json.dumps(response_for(ids), ensure_ascii=False),
                             dict(input_tokens=0, output_tokens=0, total_tokens=0))


def load():
    questions = [json.loads(l) for l in (PKG / "interview_questions_3.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]
    answers = {}
    for line in (PKG / "synthetic_answer_testcases.jsonl").read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        a = json.loads(line)
        answers[(a["case_id"], a["variant"], a["question_id"])] = a
    return questions, answers


async def ensure_user(factory, email):
    # Reuse the R24-audited fixture: a throwaway candidate WITH a real profile,
    # built by Replay (0 model HTTP). One user for all 183 scripted runs.
    return await seed_user(factory)


async def find_jobs(factory):
    from sqlalchemy import select
    out = {}
    async with factory() as db:
        all_jobs = (await db.execute(select(Job, Company).join(Company, Job.company_id == Company.id))).all()
        for case, (ckey, tkey) in CASE_JOB.items():
            match = next((j for j, c in all_jobs if ckey in c.canonical_name and tkey in j.canonical_title), None)
            if match is None:
                match = next((j for j, c in all_jobs if ckey in c.canonical_name), None)
            out[case] = (match.id, match.company_id) if match else (all_jobs[0][0].id, all_jobs[0][1].id)
    return out


async def main() -> int:
    questions, answers = load()
    engine = create_async_engine(DSN)
    factory = async_sessionmaker(engine, expire_on_commit=False)
    jobs = await find_jobs(factory)
    report = {"round": "R123-3", "mode": "OFFLINE REPLAY / 0 model HTTP", "started_at": datetime.now(timezone.utc).isoformat(),
              "note": "scripted questions from package; grading deterministic from answer text; hidden key_points/red_flag never sent to evaluated model",
              "cases": {}, "runs": []}
    import os
    limit = int(os.getenv("R123_LIMIT", "0"))
    if limit:
        questions = questions[:limit]
    variants = ("strong", "blank", "incorrect")
    uid = await ensure_user(factory, "r123-replay-synthetic@example.com")
    errors = []
    for q in questions:
        case, qid = q["case_id"], q["question_id"]
        job_id, company_id = jobs[case]
        for variant in variants:
            ans = answers.get((case, variant, qid))
            if not ans:
                errors.append(f"missing answer {case}/{variant}/{qid}")
                continue
            # topic from the package is audit metadata only; the Replay question
            # provider must pick a LEGAL candidate from the session's own space,
            # so let it infer the topic from the question text instead.
            # Non-empty expected_points/dimension: empty/None fails the product
            # schema and would trigger a StructuredOutput repair path whose
            # message shape the R24 fixture does not implement.
            ep = [q.get("stage") or q.get("topic") or "题目要点"]
            dim = (q.get("topic") or "技术能力")[:50]
            main = PlainQuestionReplay(ans["question"], ep, dim)
            evaluator = DeterministicEvaluation(variant)
            core = MockInterviewService(factory, ModelRouter({"interview_main": main, "answer_evaluation": evaluator}))
            try:
                session = await core.create(uid, CreateSessionRequest(
                    company_id=company_id, job_id=job_id, question_count=1,
                    interviewer_skill_id=SKILL[case], adaptive_interview=False,
                    training_mode=None))
                first = await core.start(session["id"], uid)
                result = await core.answer(session["id"], uid, first["question_id"],
                                           uuid.uuid4().hex, ans["answer"])
                detail = await core.detail(session["id"], uid)
                # read persisted evaluation
                from sqlalchemy import select
                from interview_api.modules.interview.models import InterviewEvaluation
                async with factory() as db:
                    ev = (await db.execute(select(InterviewEvaluation).where(
                        InterviewEvaluation.session_id == session["id"]))).scalars().first()
                scores = {d: getattr(ev, d) for d in DIMS} if ev else {}
                # product scores are 1..5; package expected_band is 10-point.
                overall = round(sum(scores.values()) / len(DIMS) * 2, 2) if scores else None
                band = ans.get("expected_band") or [None, None]
                in_band = bool(overall is not None and band[0] <= overall <= band[1])
                report["runs"].append({
                    "case": case, "qid": qid, "variant": variant, "session_id": session["id"],
                    "status": detail.get("status"), "stage": q.get("stage"), "topic": q.get("topic"),
                    "question": ans["question"][:200], "answer": ans["answer"][:200],
                    "evaluation_id": ev.id if ev else None, "scores": scores, "overall": overall,
                    "expected_band": band, "in_band": in_band,
                    "red_flag": q.get("red_flag", "")[:120],  # audit only, never sent to model
                })
            except Exception as exc:
                import traceback
                if not errors:
                    traceback.print_exc()
                errors.append(f"{case}/{variant}/{qid}: {type(exc).__name__}: {exc}"[:300])
    # Coach: one report per case using a completed 'strong' session
    for case in CASE_JOB:
        strong = next((r for r in report["runs"] if r["case"] == case and r["variant"] == "strong"), None)
        if strong:
            try:
                report_svc = InterviewReportService(factory, ModelRouter({"interview_coach": ReplayCoach()}))
                coach = await report_svc.generate(strong["session_id"], uid)
                report["cases"][case] = {"coach_session": strong["session_id"],
                                          "coach_status": coach.get("generation_status")}
            except Exception as exc:
                report["cases"][case] = {"coach_error": f"{type(exc).__name__}: {exc}"[:200]}
    report["errors"] = errors
    report["counts"] = {"questions": len(questions), "runs": len(report["runs"]),
                        "expected_runs": len(questions) * 3, "errors": len(errors)}
    report["in_band_by_variant"] = {
        v: {"total": sum(1 for r in report["runs"] if r["variant"] == v),
            "in_band": sum(1 for r in report["runs"] if r["variant"] == v and r["in_band"])}
        for v in variants}
    report["finished_at"] = datetime.now(timezone.utc).isoformat()
    (OUT / "three_interviews_replay.json").write_text(json.dumps(report, ensure_ascii=False, indent=1, default=str), encoding="utf-8")
    print(json.dumps({"counts": report["counts"], "in_band": report["in_band_by_variant"],
                      "cases": report["cases"], "errors": errors[:5]}, ensure_ascii=False, indent=1))
    await engine.dispose()
    return 0 if not errors and len(report["runs"]) == len(questions) * 3 else 2


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
